#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Lang {
    English,
    Bokmal,
    Nynorsk,
    Swedish,
    Danish,
    German,
    Dutch,
    French,
    Spanish,
    Italian,
    Portuguese,
    Finnish,
    Polish,
    Icelandic,
    Czech,
}

impl Lang {
    pub const ALL: &[Self] = &[
        Self::Bokmal,
        Self::Nynorsk,
        Self::English,
        Self::Swedish,
        Self::Danish,
        Self::Icelandic,
        Self::German,
        Self::Dutch,
        Self::French,
        Self::Spanish,
        Self::Italian,
        Self::Portuguese,
        Self::Finnish,
        Self::Polish,
        Self::Czech,
    ];

    pub fn code(self) -> &'static str {
        match self {
            Self::English => "en",
            Self::Bokmal => "nb",
            Self::Nynorsk => "nn",
            Self::Swedish => "sv",
            Self::Danish => "da",
            Self::German => "de",
            Self::Dutch => "nl",
            Self::French => "fr",
            Self::Spanish => "es",
            Self::Italian => "it",
            Self::Portuguese => "pt",
            Self::Finnish => "fi",
            Self::Polish => "pl",
            Self::Icelandic => "is",
            Self::Czech => "cs",
        }
    }

    pub fn native_name(self) -> &'static str {
        match self {
            Self::English => "English",
            Self::Bokmal => "Norsk bokmål",
            Self::Nynorsk => "Norsk nynorsk",
            Self::Swedish => "Svenska",
            Self::Danish => "Dansk",
            Self::German => "Deutsch",
            Self::Dutch => "Nederlands",
            Self::French => "Français",
            Self::Spanish => "Español",
            Self::Italian => "Italiano",
            Self::Portuguese => "Português",
            Self::Finnish => "Suomi",
            Self::Polish => "Polski",
            Self::Icelandic => "Íslenska",
            Self::Czech => "Čeština",
        }
    }

    pub fn from_code(code: &str) -> Option<Self> {
        match code.trim().to_ascii_lowercase().as_str() {
            "en" => Some(Self::English),
            "nb" | "no" => Some(Self::Bokmal),
            "nn" => Some(Self::Nynorsk),
            "sv" => Some(Self::Swedish),
            "da" => Some(Self::Danish),
            "de" => Some(Self::German),
            "nl" => Some(Self::Dutch),
            "fr" => Some(Self::French),
            "es" => Some(Self::Spanish),
            "it" => Some(Self::Italian),
            "pt" => Some(Self::Portuguese),
            "fi" => Some(Self::Finnish),
            "pl" => Some(Self::Polish),
            "is" => Some(Self::Icelandic),
            "cs" => Some(Self::Czech),
            _ => None,
        }
    }

    pub fn from_locale(locale: &str) -> Option<Self> {
        let primary = locale
            .split(['.', '@'])
            .next()
            .unwrap_or(locale)
            .replace('_', "-");
        let lang = primary.split('-').next().unwrap_or(&primary);
        Self::from_code(lang)
    }

    pub fn text(self) -> &'static UiText {
        match self {
            Self::English => &EN,
            Self::Bokmal => &NB,
            Self::Nynorsk => &NN,
            Self::Swedish => &SV,
            Self::Danish => &DA,
            Self::German => &DE,
            Self::Dutch => &NL,
            Self::French => &FR,
            Self::Spanish => &ES,
            Self::Italian => &IT,
            Self::Portuguese => &PT,
            Self::Finnish => &FI,
            Self::Polish => &PL,
            Self::Icelandic => &IS,
            Self::Czech => &CS,
        }
    }
}

